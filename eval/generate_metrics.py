"""Generate docs/metrics.md from eval/results/*.json (Phase 4.6).

Never edit docs/metrics.md by hand: it is regenerated by `make eval`.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "eval" / "results"


def load(name: str):
    path = RESULTS / name
    if not path.exists():
        return None
    return json.loads(path.read_text(encoding="utf-8"))


def _pct(x):
    return f"{100 * x:.1f}%"


def main() -> int:
    meddocan = load("meddocan.json")
    promptbench = load("promptbench.json")
    utility = load("utility.json")
    cost = load("cost.json")

    lines = [
        "# Evaluation",
        "",
        "> Generated by `make eval` from `eval/results/*.json`. Do not edit by hand.",
        "",
        "Pukara's anonymization engine is the detection pipeline of carmina3: a",
        "BERT model (`bsc-bio-ehr-es-carmen-anon`) plus regex rules. All numbers",
        "below are produced by scripts in `eval/` and versioned under",
        "`eval/results/`.",
        "",
        "## Contamination status",
        "",
        "- **CARMEN-I is retired as a headline metric**: the model was fine-tuned on",
        "  CARMEN-I and no public train/test split could be determined (see",
        "  `docs/dev/eval-contamination.md`). Any CARMEN-I number is",
        "  *in-distribution, upper bound, possible train overlap* — an open",
        "  question for the authors.",
        "- **MEDDOCAN is clean**: the model was not trained on MEDDOCAN. The",
        "  calibration partition (`train`, 500 docs) is excluded; evaluation uses",
        "  `dev` + `test` (500 docs).",
        "",
        "## MEDDOCAN (dev + test, out-of-distribution)",
        "",
    ]

    if meddocan:
        wl = meddocan["word_level"]
        ss = meddocan["span_strict"]
        sr = meddocan["span_relaxed"]
        lk = meddocan["leakage"]
        lines += [
            f"- Mode: `{meddocan['mode']}`; documents: {meddocan['documents']};",
            f"  revision `{meddocan['code_revision'][:12]}`.",
            "",
            "| Level | Precision | Recall | F1 | F1 CI95 |",
            "|---|---|---|---|---|",
            f"| Word | {_pct(wl['precision'])} | {_pct(wl['recall'])} | "
            f"{_pct(wl['f1'])} | {_ci(wl)} |",
            f"| Span strict | {_pct(ss['precision'])} | {_pct(ss['recall'])} | "
            f"{_pct(ss['f1'])} | — |",
            f"| Span relaxed | {_pct(sr['precision'])} | {_pct(sr['recall'])} | "
            f"{_pct(sr['f1'])} | {_ci(sr)} |",
            "",
            f"**Document-level leakage** (docs with ≥1 missed direct identifier): "
            f"{lk['leaked_docs']} / {lk['total_docs']} ({_pct(lk['rate'])}).",
            "",
            "### Per-class (span strict)",
            "",
            "| Class | Precision | Recall | F1 | Support |",
            "|---|---|---|---|---|",
        ]
        for lab in sorted(meddocan["per_class"]):
            c = meddocan["per_class"][lab]
            lines.append(f"| {lab} | {_pct(c['precision'])} | {_pct(c['recall'])} | "
                         f"{_pct(c['f1'])} | {c['support']} |")
        lines.append("")
    else:
        lines += [
            "No MEDDOCAN results yet. Run `python -m eval.meddocan` (TODO: the",
            "BERT/combined modes need the gated model under `models/`).",
            "",
        ]

    lines += [
        "## Synthetic prompt benchmark",
        "",
    ]
    if promptbench:
        ss = promptbench["span_strict"]
        sr = promptbench["span_relaxed"]
        co = promptbench["coreference"]
        lines += [
            f"- Mode: `{promptbench['mode']}`; prompts: {promptbench['n_prompts']}.",
            "",
            "| Metric | Value |",
            "|---|---|",
            f"| Span strict F1 | {_pct(ss['f1'])} |",
            f"| Span relaxed F1 | {_pct(sr['f1'])} |",
            f"| Coreference consistency | {_pct(co['consistency_rate'])} "
            f"({co['consistent_entities']}/{co['total_entities_with_detected_mentions']}) |",
            f"| Placeholder collisions | {promptbench['collisions']} |",
            "",
            "_Limitations: synthetic and templated (optimistic upper bound); possible",
            "circularity if templates and regex rules share authors._",
            "",
        ]
    else:
        lines += ["No prompt benchmark results yet.\n"]

    lines += ["## Utility preservation (no LLM)", ""]
    if utility:
        rt = utility["roundtrip"]
        lines += [
            f"- Round-trip exact (`deanonymize(anonymize(x)) == x`): "
            f"{rt['failures']} failures / {rt['texts']} texts "
            f"({_pct(rt['rate'])}). Failures are bugs.",
            "",
            "| Perturbation | Restored | Rate |",
            "|---|---|---|",
        ]
        for name, r in utility["robustness"].items():
            lines.append(f"| {name} | {r['restored']}/{r['total']} | {_pct(r['rate'])} |")
        lines.append("")
    else:
        lines += ["No utility results yet.\n"]

    lines += ["## Cost", ""]
    if cost:
        a = cost["anonymization_latency_ms"]
        lines += [
            f"- Hardware: `{cost['hardware']['cpu']}` / `{cost['hardware']['platform']}`.",
            f"- Anonymization (regex, CPU): p50 {a['p50']} ms, p95 {a['p95']} ms "
            f"over {a['documents']} documents.",
            f"- Client peak memory (tracemalloc): "
            f"{cost['client_peak_memory_bytes'] / 1024 / 1024:.1f} MiB.",
            "",
            "| Payload | Encrypt+decrypt p50 | p95 |",
            "|---|---|---|",
        ]
        for row in cost["encryption_ms"]:
            lines.append(f"| {row['size_bytes']} B | {row['p50_ms']} ms | "
                         f"{row['p95_ms']} ms |")
        lines.append("")
    else:
        lines += ["No cost results yet.\n"]

    out = ROOT / "docs" / "metrics.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("[metrics] docs/metrics.md generado")
    return 0


def _ci(level):
    lo, hi = level["f1_ci95"]
    return f"{_pct(lo)}–{_pct(hi)}"


if __name__ == "__main__":
    sys.exit(main())
